#pragma once

// 권한이 바뀐 노드의 협업 세션을 정리·통보한다 (TASK_11 §12.9).
//
// 왜 컨트롤러 계층인가: "누가 어떻게 바뀌었는지"는 DB 함수가 계산하지만, 그 결과를 집행하는 곳이
// 둘로 나뉘어 있다 — 제어 소켓(/api/github/ws)은 이 서버(C++)가 직접 닫고, 문서 소켓(/collab/)은
// collab 사이드카가 닫는다. collab 클라이언트(`utils/collab/CollabClient`)는 앞쪽만 알기 때문에
// 둘을 함께 다룰 수 없다. 그래서 두 소켓을 아는 이 계층이 오케스트레이션을 맡는다.
namespace api
{
/**
 * 노드 권한이 바뀐 뒤(역할 정의·역할 배정 변경, 노드 이동) 그 서브트리 저장소에서 작업 중인
 * 사용자에게 새 권한을 반영한다 (§12.9).
 *
 * - 쓰기 권한이 바뀐 사람: `perm` 프레임으로 읽기 전용 전환·복구(세션은 유지).
 * - 보기 권한을 잃은 사람: 그 저장소에서 **강제 이탈**시킨다(제어 소켓 + 문서 소켓).
 *
 * 응답을 기다리지 않는다 — 권한 변경은 사용자 요청의 결과가 아니므로, 통보가 실패해도 원래
 * 요청을 실패시키지 않는다(로그만 남긴다).
 */
void notifyAuthorityChangedAsync(int node_id);

/**
 * 노드가 삭제(소프트 딜리트)됐을 때 그 서브트리 저장소의 협업 세션을 끊는다 (§12.9).
 *
 * 노드 삭제는 소프트 딜리트라 저장소 행도 작업 트리도 남는다. 그래서 "지금 붙어 있는 세션을
 * 끊는 일"과 "다시 못 붙게 막는 일"을 나눠서 한다 — 여기서는 전자만 한다(후자는 접속 등록과
 * 경로 해석의 P0815 가 막는다).
 *
 * 삭제 응답은 기다리지 않는다 — DB 조회와 HTTP 통보가 섞여 있어 워커 스레드에 띄운다.
 */
void closeNodeSessionsAsync(int node_id);
}  // namespace api
